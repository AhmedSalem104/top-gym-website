export const translations = { ar, en };
export const t = (locale: Locale) => translations[locale];
export const money = (value: number, locale: Locale) =>
  new Intl.NumberFormat(locale === 'ar' ? 'ar-EG' : 'en-EG', {
    style: 'currency',
    currency: business.currency,
    maximumFractionDigits: 0,
  }).format(value);
export const formatTime = (minutes: number, locale: Locale) => {
  if (minutes === 1440) return t(locale).midnight;
  return new Intl.DateTimeFormat(locale === 'ar' ? 'ar-EG' : 'en-EG', {
    timeZone: 'UTC',
    hour: 'numeric',
    minute: '2-digit',
    hour12: true,
  }).format(new Date(Date.UTC(2026, 0, 1, Math.floor(minutes / 60), minutes % 60)));
};
