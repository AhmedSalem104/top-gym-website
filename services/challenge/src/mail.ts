const escape = (s: string) =>
  s.replace(
    /[&<>"']/g,
    (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!,
  );
export interface MailData {
  name: string;
  phone: string;
  email?: string;
  score: number;
  coupon?: { code: string; state: string; expires: number };
  completed: number;
  locale: 'ar' | 'en';
  terms: { ar: string; en: string };
  attribution: Record<string, string>;
  questions: { question: Question; answer: number | null; timedOut: boolean; correct: boolean }[];
}
export function challengeEmail(data: MailData, audience: 'admin' | 'customer') {
  const ar = data.locale === 'ar';
  const date = (n: number) =>
    new Intl.DateTimeFormat(ar ? 'ar-EG' : 'en-GB', {
      dateStyle: 'medium',
      timeStyle: 'short',
      timeZone: 'Africa/Cairo',
    }).format(n);
  const subject =
    audience === 'admin'
      ? `[TOP GYM WEBSITE] New Fitness Challenge Participant — ${data.score * 10}% Discount`
      : 'TOP GYM — Your Fitness Challenge Result';
  const entries: [string, string][] = [
    ['Name / الاسم', data.name],
    ['Score / النتيجة', `${data.score} / 3`],
    ['Discount / الخصم', `${data.score * 10}%`],
    ['Completed / اكتمل', date(data.completed) + ' · Africa/Cairo'],
  ];
  if (audience === 'admin') entries.push(['Phone / الهاتف', data.phone]);
  if (data.email) entries.push(['Email / البريد', data.email]);
  if (data.coupon)
    entries.push(
      ['Coupon / الكوبون', data.coupon.code],
      [
        'Status / الحالة',
        ar
          ? { issued: 'متاح', redeemed: 'مستخدم', expired: 'منتهي', voided: 'ملغى' }[
              data.coupon.state
            ] || data.coupon.state
          : data.coupon.state,
      ],
      ['Expires / ينتهي', date(data.coupon.expires)],
    );
  else
    entries.push([
      'Coupon / الكوبون',
      ar ? 'لا يوجد كوبون لهذه النتيجة' : 'No coupon for this result',
    ]);
  entries.push(['Terms / الشروط', data.terms[data.locale]]);
  if (audience === 'admin') {
    entries.push([
      'Campaign / الحملة',
      Object.entries(data.attribution)
        .map(([k, v]) => `${k}: ${v}`)
        .join(' · ') || '—',
    ]);
    data.questions.forEach((q, i) =>
      entries.push([
        `${i + 1}. ${q.question.question[data.locale]}`,
        [
          ar ? 'الإجابة: ' : 'Answer: ',
          q.timedOut
            ? ar
              ? 'انتهت المهلة'
              : 'Timed out'
            : q.answer === null
              ? '—'
              : q.question.options[q.answer][data.locale],
          ar ? ' | الصحيحة: ' : ' | Correct: ',
          q.question.options[q.question.correct][data.locale],
          q.correct ? ' ✓' : ' ✕',
        ].join(''),
      ]),
    );
  }
  const rows = entries
    .map(
      ([label, value]) =>
        `<tr><td style="padding:14px 24px;border-bottom:1px solid #e5e7eb"><div style="font:12px Arial;color:#565b63;margin-bottom:6px">${escape(label)}</div><div dir="auto" style="font:16px/1.7 Arial;color:#17191c;overflow-wrap:anywhere">${escape(value).replace(/\n/g, '<br>')}</div></td></tr>`,
    )
    .join('');
  return {
    subject,
    text: [
      'TOP GYM WEBSITE — FITNESS CHALLENGE',
      ...entries.map(([k, v]) => `${k}\n${v}`),
      'This notification was generated by the TOP GYM website fitness challenge.',
    ].join('\n\n'),
    html: `<!doctype html><html lang="${data.locale}" dir="${ar ? 'rtl' : 'ltr'}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width"></head><body style="margin:0;background:#eef0f2;padding:20px 8px"><table role="presentation" width="100%" cellspacing="0" cellpadding="0"><tr><td align="center"><table role="presentation" width="600" cellspacing="0" cellpadding="0" style="width:100%;max-width:600px;background:#ffffff;border:1px solid #e59500"><tr><td style="padding:30px 24px;background:#0b0d0f;color:#f8f9fa"><p style="font:bold 30px Arial;margin:0;color:#e59500">TOP GYM</p><p style="font:11px Arial;letter-spacing:2px;color:#f8f9fa">OFFICIAL WEBSITE NOTIFICATION</p><h1 style="font:bold 24px/1.5 Arial;color:#f8f9fa">${ar ? 'نتيجة تحدي TOP GYM' : 'FITNESS CHALLENGE RESULT'}</h1><p style="font:bold 44px Arial;color:#e59500;margin:12px 0">${data.score * 10}%</p><p style="font:15px Arial;color:#f8f9fa">${data.score} / 3 · TOP GYM WEBSITE</p></td></tr>${rows}<tr><td style="padding:24px;font:12px/1.8 Arial;color:#565b63">TOP GYM — CUSTOMER EXPERIENCE<br>تم إرسال هذه الرسالة تلقائيًا من تحدي توب جيم.<br>This notification was generated by the TOP GYM website fitness challenge.</td></tr></table></td></tr></table></body></html>`,
  };
}
export function mailData(s: Store, sessionId: string): MailData {
  const session = s.get<Session>('SELECT * FROM challenge_sessions WHERE id=?', sessionId)!;
  const p = s.get<{ details_cipher: string; phone_cipher: string }>(
    'SELECT p.details_cipher,i.phone_cipher FROM participants p JOIN verified_phone_identities i ON i.id=p.phone_id WHERE p.session_id=?',
    sessionId,
  )!;
  const details = JSON.parse(unseal(s.config.CHALLENGE_DATA_KEY, p.details_cipher)) as Details;
  const coupon = s.get<Coupon>('SELECT * FROM coupons WHERE session_id=?', sessionId);
  const policy = JSON.parse(
    s.get<{ body: string }>(
      'SELECT body FROM discount_policy_versions WHERE version=?',
      session.policy_version,
    )!.body,
  ) as Policy;
  const questions = s
    .all<Round & { option_id: string | null; timed_out: number; correct: number }>(
      'SELECT q.*,a.option_id,a.timed_out,a.correct FROM challenge_session_questions q JOIN challenge_answers a ON a.session_id=q.session_id AND a.ordinal=q.ordinal WHERE q.session_id=? ORDER BY q.ordinal',
      sessionId,
    )
    .map((q) => ({
      question: JSON.parse(q.snapshot) as Question,
      answer:
        (JSON.parse(q.option_order) as { id: string; index: number }[]).find(
          (o) => o.id === q.option_id,
        )?.index ?? null,
      timedOut: Boolean(q.timed_out),
      correct: Boolean(q.correct),
    }));
  return {
    ...details,
    phone: unseal(s.config.CHALLENGE_DATA_KEY, p.phone_cipher),
    score: session.score,
    completed: session.completed_at!,
    locale: session.locale,
    terms: policy.terms,
    attribution: JSON.parse(session.attribution) as Record<string, string>,
    questions,
    coupon: coupon
      ? {
          code: unseal(s.config.CHALLENGE_DATA_KEY, coupon.code_cipher),
          state: coupon.state === 'issued' && coupon.expires <= s.now() ? 'expired' : coupon.state,
          expires: coupon.expires,
        }
      : undefined,
  };
}
export type MailSender = (
  data: MailData,
  audience: 'admin' | 'customer',
  id: string,
) => Promise<void>;
export function smtpSender(s: Store): MailSender {
  return async (data, audience, id) => {
    const c = s.config;
    if (!c.SMTP_USER || !c.SMTP_APP_PASSWORD || !c.CHALLENGE_ADMIN_EMAIL)
      throw Object.assign(new Error('mail_unconfigured'), { code: 'ENOCONFIG' });
    const transport = nodemailer.createTransport({
      host: c.SMTP_HOST,
      port: Number(c.SMTP_PORT),
      secure: c.SMTP_PORT === '465',
      requireTLS: true,
      auth: { user: c.SMTP_USER, pass: c.SMTP_APP_PASSWORD },
      tls: { minVersion: 'TLSv1.2', rejectUnauthorized: true },
      connectionTimeout: 8000,
      greetingTimeout: 8000,
      socketTimeout: 12000,
      logger: false,
      debug: false,
      disableFileAccess: true,
      disableUrlAccess: true,
    });
    const to = audience === 'admin' ? c.CHALLENGE_ADMIN_EMAIL : data.email;
    if (!to) throw Object.assign(new Error('recipient_missing'), { code: 'EENVELOPE' });
    try {
      const result = await transport.sendMail({
        ...challengeEmail(data, audience),
        from: { name: 'TOP GYM Website', address: c.SMTP_USER },
        to,
        replyTo: audience === 'admin' ? data.email : undefined,
        messageId: `<topgym-challenge-${id}@${c.SMTP_USER.split('@')[1]}>`,
        headers: { 'Auto-Submitted': 'auto-generated', 'X-Auto-Response-Suppress': 'All' },
      });
      if (!result.accepted.some((x) => String(x).toLowerCase() === to.toLowerCase()))
        throw Object.assign(new Error('rejected'), { code: 'EREJECTED' });
    } finally {
      transport.close();
    }
  };
}
export async function deliverNext(s: Store, send: MailSender) {
  s.run(
    "UPDATE email_delivery_jobs SET state='uncertain',last_code='INTERRUPTED' WHERE state='sending' AND locked_at<?",
    s.now() - 120000,
  );
  const job = s.atomic(() => {
    const row = s.get<{
      id: string;
      session_id: string;
      audience: 'admin' | 'customer';
      attempts: number;
    }>(
      "SELECT * FROM email_delivery_jobs WHERE state='queued' AND available_at<=? ORDER BY available_at LIMIT 1",
      s.now(),
    );
    if (row)
      s.run(
        "UPDATE email_delivery_jobs SET state='sending',locked_at=?,attempts=attempts+1 WHERE id=?",
        s.now(),
        row.id,
      );
    return row;
  });
  if (!job) return;
  try {
    await send(mailData(s, job.session_id), job.audience, job.id);
    s.run("UPDATE email_delivery_jobs SET state='accepted',last_code=NULL WHERE id=?", job.id);
  } catch (error) {
    const code = (error as { code?: string }).code || 'UNKNOWN';
    const definitive = ['EAUTH', 'EENVELOPE', 'EREJECTED', 'ENOCONFIG', 'EDNS'].includes(code);
    const state = definitive ? (job.attempts < 4 ? 'queued' : 'failed') : 'uncertain';
    s.run(
      'UPDATE email_delivery_jobs SET state=?,available_at=?,last_code=? WHERE id=?',
      state,
      s.now() + Math.min(3600000, 60000 * 2 ** job.attempts),
      definitive ? code : 'UNCERTAIN',
      job.id,
    );
  }
}
